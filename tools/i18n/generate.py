#!/usr/bin/env python3
"""Generates the Flutter and native string tables from tools/i18n/*.json.

Each JSON file maps an English string (exactly as it appears in the UI) to its
translations in the order listed in LANGS. Run from anywhere:

    python3 tools/i18n/generate.py
"""
import json
import pathlib

LANGS = ["hi", "mr", "bn", "ta", "te"]
ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ["dashboard.json", "tools.json", "chat_extra.json", "native.json"]
DART_OUT = ROOT / "flutter/lib/l10n/app_strings.dart"
KOTLIN_OUT = ROOT / "app/src/main/java/com/dhalam/ap/AppStrings.kt"
CHUNK = 40


def load():
    table = {}
    here = pathlib.Path(__file__).parent
    for name in SOURCES:
        for key, values in json.loads((here / name).read_text("utf-8")).items():
            if len(values) != len(LANGS):
                raise SystemExit(f"{name}: '{key}' has {len(values)} translations")
            table[key] = values
    return table


def esc(text):
    return text.replace("\\", "\\\\").replace("$", "\\$").replace("\n", "\\n")


def dart_str(text):
    return "'" + esc(text).replace("'", "\\'") + "'"


def kotlin_str(text):
    return '"' + esc(text).replace('"', '\\"') + '"'


def write_dart(table):
    lines = [
        "// GENERATED by tools/i18n/generate.py from tools/i18n/*.json. Do not edit.",
        "",
        "const appLanguageOrder = <String>["
        + ", ".join(dart_str(code) for code in LANGS)
        + "];",
        "",
        "/// English text -> translations, in [appLanguageOrder].",
        "const appStringTable = <String, List<String>>{",
    ]
    for key, values in table.items():
        joined = ", ".join(dart_str(v) for v in values)
        lines.append(f"  {dart_str(key)}: [{joined}],")
    lines.append("};")
    DART_OUT.write_text("\n".join(lines) + "\n", "utf-8")


def write_kotlin(table):
    items = list(table.items())
    chunks = [items[i : i + CHUNK] for i in range(0, len(items), CHUNK)]
    lines = [
        "package com.dhalam.ap",
        "",
        "// GENERATED by tools/i18n/generate.py from tools/i18n/*.json. Do not edit.",
        "",
        "internal val appLanguageOrder = listOf("
        + ", ".join(kotlin_str(code) for code in LANGS)
        + ")",
        "",
    ]
    for index, chunk in enumerate(chunks):
        lines.append(
            f"private fun stringsPart{index}(): Map<String, List<String>> = mapOf("
        )
        entries = []
        for key, values in chunk:
            joined = ", ".join(kotlin_str(v) for v in values)
            entries.append(f"    {kotlin_str(key)} to listOf({joined})")
        lines.append(",\n".join(entries))
        lines.append(")")
        lines.append("")
    parts = " + ".join(f"stringsPart{i}()" for i in range(len(chunks)))
    lines.append("/** English text -> translations, in [appLanguageOrder]. */")
    lines.append(
        f"internal val appStringTable: Map<String, List<String>> by lazy {{ {parts} }}"
    )
    KOTLIN_OUT.write_text("\n".join(lines) + "\n", "utf-8")


if __name__ == "__main__":
    data = load()
    write_dart(data)
    write_kotlin(data)
    print(f"{len(data)} strings x {len(LANGS)} languages")
